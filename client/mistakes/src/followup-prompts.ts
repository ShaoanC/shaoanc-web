function sample(pool: string[], count: number) {
  const remaining = [...pool];
  return Array.from({ length: count }, () => remaining.splice(Math.floor(Math.random() * remaining.length), 1)[0]);
}

export function pickFollowupPrompts(subjectId: string | null) {
  const subject = subjectId && bySubject[subjectId];
  return subject ? [...sample(subject, 3), ...sample(general, 1)] : sample(general, 4);
}
